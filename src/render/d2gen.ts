/**
 * Resolved model → D2 source for the topology diagram.
 *
 * Pure string building. The caller supplies the icons, so the same generator
 * produces both the readable source shown in the "D2 source" tab (icons as
 * paths) and the source that is rendered (icons inlined as data URIs).
 */
import { formatIp, formatSubnet } from '../ip';
import type { RConnection, RDevice, REndpoint, ResolvedModel } from '../model/resolve';

export interface IconInfo {
  /** What goes after `icon:` — a path, a data URI or an https URL. */
  href: string;
  width: number;
  height: number;
}

export interface D2Options {
  /** Looks up the icon for a device's `icon` reference; undefined draws a plain box instead. */
  icon: (ref: string) => IconInfo | undefined;
}

export interface D2Settings {
  layout: 'dagre' | 'elk';
  themeID: number;
  sketch: boolean;
  dark: boolean;
}

const THEMES = { default: 0, dark: 200, sketch: 0 } as const;

/** Compile and render options that follow from the `diagram` block. */
export function d2Settings(model: ResolvedModel): D2Settings {
  const theme = model.diagram.theme ?? 'default';
  return { layout: model.diagram.layout ?? 'dagre', themeID: THEMES[theme], sketch: theme === 'sketch', dark: theme === 'dark' };
}

/** A double-quoted D2 string. `$` is escaped so that `${…}` is not taken as a substitution. */
export function quote(text: string): string {
  return `"${text.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\$/g, '\\$').replace(/\r?\n/g, '\\n')}"`;
}

/** Blends a `#rrggbb` colour towards a base colour; `amount` is the share of `hex`. */
function tint(hex: string, base: string, amount: number): string {
  const parse = (h: string): number[] => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16));
  const [a, b] = [parse(hex), parse(base)];
  return `#${a.map((channel, i) => Math.round(channel * amount + b[i] * (1 - amount)).toString(16).padStart(2, '0')).join('')}`;
}

const DEFAULT_SITE_COLOR = '#51606f';
const LOCKED_COLOR = '#dc2626';
const TUNNEL_COLORS = ['#c2410c', '#7c3aed', '#0f766e', '#be185d', '#4d7c0f'];

export function generateD2(model: ResolvedModel, options: D2Options): string {
  const settings = d2Settings(model);
  const paper = settings.dark ? '#1e1e2e' : '#ffffff';
  const out: string[] = [];
  const devicePath = new Map<string, string>();

  out.push(
    '# Generated by netplan from the YAML on the left. Edit the YAML, not this file;',
    '# use `diagram.extra_d2` to append your own D2.',
    '',
    'vars: {',
    '  d2-config: {',
    `    layout-engine: ${settings.layout}`,
    `    theme-id: ${settings.themeID}`,
    ...(settings.sketch ? ['    sketch: true'] : []),
    '    pad: 24',
    '  }',
    '}',
    `direction: ${model.diagram.direction ?? 'down'}`,
    '',
  );

  // Connections leave a node along the flow direction, so the name goes on the
  // other axis where no line will run through it.
  const vertical = (model.diagram.direction ?? 'down') === 'down' || model.diagram.direction === 'up';
  /** `VLAN 10` or the LAN name under an unmanaged device, so the drawing shows which network it serves. */
  const networkLine = (device: RDevice): string | undefined => {
    if (device.vlan) return `VLAN ${device.vlan.value}`;
    if (device.lan) return model.sites.find((s) => s.id === device.siteId)?.lans.find((l) => l.id === device.lan!.value)?.name ?? device.lan.value;
    return undefined;
  };
  const deviceLines = (device: RDevice, container: string): string[] => {
    devicePath.set(device.id, `${quote(container)}.${quote(device.id)}`);
    const icon = options.icon(device.icon);
    const label = quote([device.name, networkLine(device)].filter(Boolean).join('\n'));
    if (!icon) return [`  ${quote(device.id)}: ${label}`];
    return [
      `  ${quote(device.id)}: ${label} {`,
      '    shape: image',
      `    icon: ${quote(icon.href)}`,
      `    width: ${icon.width}`,
      `    height: ${icon.height}`,
      ...(vertical ? ['    label.near: outside-right-center'] : []),
      '  }',
    ];
  };

  if (model.external.length) out.push('# External networks: not yours to change, so drawn with a red dashed border.');
  for (const group of model.external) {
    out.push(
      `${quote(group.id)}: ${quote(group.name)} {`,
      '  style: {',
      `    stroke: ${quote(LOCKED_COLOR)}`,
      '    stroke-dash: 4',
      '    stroke-width: 2',
      `    fill: ${quote(tint(LOCKED_COLOR, paper, 0.06))}`,
      '    font-size: 18',
      '  }',
      ...group.devices.flatMap((d) => deviceLines(d, group.id)),
      '}',
      '',
    );
  }

  if (model.sites.length) out.push('# Sites: one container each, labelled with name and supernet.');
  for (const site of model.sites) {
    const color = site.color ?? DEFAULT_SITE_COLOR;
    const label = site.supernet ? `${site.name}\n${formatSubnet(site.supernet)}` : site.name;
    out.push(
      `${quote(site.id)}: ${quote(label)} {`,
      '  style: {',
      `    stroke: ${quote(color)}`,
      '    stroke-width: 2',
      `    fill: ${quote(tint(color, paper, 0.12))}`,
      '    font-size: 18',
      '  }',
      ...site.devices.flatMap((d) => deviceLines(d, site.id)),
      '}',
      '',
    );
  }

  /** `f0/0 · 10.255.0.1`, or whichever part is known. */
  const endLabel = (end: REndpoint): string | undefined => {
    const parts = [end.ifName, end.ip === undefined ? undefined : formatIp(end.ip)].filter(Boolean);
    return parts.length ? parts.join(' · ') : undefined;
  };

  const edge = (a: string, b: string, label: string | undefined, body: string[]): void => {
    const head = `${devicePath.get(a)} -- ${devicePath.get(b)}${label ? `: ${quote(label)}` : ''}`;
    if (body.length === 0) out.push(head);
    else out.push(`${head} {`, ...body.map((line) => `  ${line}`), '}');
  };

  const connectionLabel = (c: RConnection): string | undefined => {
    if (c.kind === 'link') return [c.name, c.subnet ? formatSubnet(c.subnet) : undefined].filter(Boolean).join('\n');
    if (c.kind === 'wan') return [c.name, c.subnet ? formatSubnet(c.subnet) : undefined].filter(Boolean).join('\n') || undefined;
    if (c.trunkVlans) return `trunk ${c.trunkVlans.join(', ') || '(no VLANs)'}`;
    return undefined;
  };

  // dagre fans connections out around a node, so there is room for a label at
  // each end. ELK brings them in side by side, where end labels would pile up;
  // there the ends are named inside the middle label instead.
  const endsInMiddle = settings.layout === 'elk';
  const deviceName = (id: string): string => model.devices.get(id)?.name ?? id;

  const drawable = model.connections.filter((c) => devicePath.has(c.a.deviceId) && devicePath.has(c.b.deviceId));
  if (drawable.length) {
    out.push(
      endsInMiddle
        ? '# Physical connections. Each label names both ends as device interface · address.'
        : '# Physical connections. The labels at each end are interface · address.',
    );
  }
  for (const c of drawable) {
    const body: string[] = [];
    const [from, to] = [endLabel(c.a), endLabel(c.b)];
    let label = connectionLabel(c);
    if (endsInMiddle) {
      label = [from ? `${deviceName(c.a.deviceId)} ${from}` : undefined, label, to ? `${deviceName(c.b.deviceId)} ${to}` : undefined]
        .filter(Boolean)
        .join('\n');
    } else {
      if (from) body.push(`source-arrowhead.label: ${quote(from)}`);
      if (to) body.push(`target-arrowhead.label: ${quote(to)}`);
    }
    body.push('style.font-size: 13');
    if (c.trunkVlans) body.push('style.stroke-width: 3');
    edge(c.a.deviceId, c.b.deviceId, label || undefined, body);
  }
  if (drawable.length) out.push('');

  const tunnels = model.tunnels.filter((t) => devicePath.has(t.a.deviceId) && devicePath.has(t.b.deviceId));
  if (tunnels.length) out.push('# VPN tunnels: dashed, labelled with the tunnel subnet.');
  tunnels.forEach((tunnel, index) => {
    const color = TUNNEL_COLORS[index % TUNNEL_COLORS.length];
    const body: string[] = [];
    const [from, to] = [tunnel.a.address, tunnel.b.address].map((address) => (address ? formatIp(address.value) : undefined));
    const lines = [tunnel.name, tunnel.subnet ? formatSubnet(tunnel.subnet) : tunnel.type];
    if (endsInMiddle) {
      if (from) lines.unshift(`${deviceName(tunnel.a.deviceId)} ${from}`);
      if (to) lines.push(`${deviceName(tunnel.b.deviceId)} ${to}`);
    } else {
      if (from) body.push(`source-arrowhead.label: ${quote(from)}`);
      if (to) body.push(`target-arrowhead.label: ${quote(to)}`);
    }
    const label = lines.join('\n');
    body.push('style: {', `  stroke: ${quote(color)}`, '  stroke-dash: 5', '  stroke-width: 2', `  font-color: ${quote(color)}`, '  font-size: 13', '}');
    edge(tunnel.a.deviceId, tunnel.b.deviceId, label, body);
  });
  if (tunnels.length) out.push('');

  const extra = model.diagram.extra_d2?.trimEnd();
  if (extra) out.push('# From diagram.extra_d2:', extra, '');

  return out.join('\n');
}
